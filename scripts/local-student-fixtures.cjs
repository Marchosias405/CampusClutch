// Disposable identities for tests against the project's local Supabase stack.
const assert = require('node:assert/strict');
const { execFileSync } = require('node:child_process');
const { randomBytes, randomUUID } = require('node:crypto');
const fs = require('node:fs');
const { parseEnv } = require('node:util');

const issued = new Set();
// Alternate ports support an isolated local stack when Windows reserves the
// usual range. The host and protocol remain fixed: never permit a hosted target.
function testPort(name, fallback) {
  const value = process.env[name] || String(fallback);
  assert.match(value, /^\d{4,5}$/, 'Use a numeric local test port');
  const port = Number(value);
  assert.ok(port >= 1024 && port <= 65535, 'Use an unprivileged local test port');
  return String(port);
}
const localUrl = 'http://127.0.0.1:' + testPort('CAMPUSCLUTCH_TEST_API_PORT', 54321);
const databasePort = testPort('CAMPUSCLUTCH_TEST_DB_PORT', 54322);

function localClientConfig() {
  const file = fs.existsSync('.env.local') ? parseEnv(fs.readFileSync('.env.local', 'utf8')) : {};
  const env = { ...file, ...process.env };
  const url = env.EXPO_PUBLIC_SUPABASE_URL;
  const key = env.EXPO_PUBLIC_SUPABASE_PUBLISHABLE_KEY || env.EXPO_PUBLIC_SUPABASE_ANON_KEY;
  assert.equal(url, localUrl, 'Use the local Supabase API for the student journey');
  assert.ok(key, 'Set the local public Supabase key');
  return { url, key };
}

function sql(statement) {
  return execFileSync('psql', ['-X', '-qAt', '-w', '-h', '127.0.0.1', '-p', databasePort,
    '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-f', '-'], {
    input: statement, encoding: 'utf8', timeout: 30000, windowsHide: true,
    env: { ...process.env, PGHOSTADDR: '127.0.0.1', PGPASSWORD: 'postgres', PGCONNECT_TIMEOUT: '5' },
  }).trim();
}

function createStudentFixture() {
  const email = 'journey-' + randomUUID() + '@test.local';
  assert.equal(sql(`select exists (select from auth.users where email = '${email}')
    or exists (select from points_private.starter_grant_claims
               where email_fingerprint = points_private.email_fingerprint('${email}'));`), 'f');
  issued.add(email);
  return { email, password: randomBytes(24).toString('hex') };
}

function countStudentFixtureReports({ email }, targetType) {
  assert.ok(issued.has(email), 'Inspect only identities generated by this test process');
  assert.match(email, /^journey-[0-9a-f-]{36}@test\.local$/);
  assert.ok(['student', 'request', 'message', 'course_review'].includes(targetType));
  return Number(sql(`select count(*) from safety_private.reports r
    join auth.users u on u.id = r.reporter_id
    where u.email = '${email}' and r.target_type = '${targetType}';`));
}

function cleanupStudentFixtures(fixtures) {
  if (fixtures.length === 0) return;
  const emails = fixtures.map(({ email }) => {
    assert.ok(issued.has(email), 'Cleanup only accepts identities generated by this test process');
    assert.match(email, /^journey-[0-9a-f-]{36}@test\.local$/);
    return "'" + email + "'";
  }).join(',');
  const receipts = `select points_private.email_fingerprint(email)
    from unnest(array[${emails}]::text[]) addresses(email)`;
  const remaining = sql(`begin;
    create temporary table fixture_users on commit drop as
      select id from auth.users where email in (${emails});
    create temporary table fixture_chats on commit drop as
      select id from public.conversations where created_by in (select id from fixture_users);
    do $cleanup$ begin
      if to_regclass('safety_private.reports') is not null then
        delete from safety_private.reports
        where reporter_id in (select id from fixture_users)
           or reported_profile_id in (select id from fixture_users)
           or request_id in (select id from public.requests where owner_id in (select id from fixture_users));
      end if;
    end $cleanup$;
    delete from public.notifications where recipient_id in (select id from fixture_users);
    delete from public.request_conversations where conversation_id in (select id from fixture_chats);
    delete from public.messages where conversation_id in (select id from fixture_chats);
    delete from public.group_membership_periods where conversation_id in (select id from fixture_chats);
    delete from public.conversation_members where conversation_id in (select id from fixture_chats);
    delete from public.direct_conversation_pairs where conversation_id in (select id from fixture_chats);
    delete from public.conversations where id in (select id from fixture_chats);
    delete from public.requests where owner_id in (select id from fixture_users);
    delete from auth.users where id in (select id from fixture_users);
    delete from realtime.messages where topic in (
      select 'messages:' || id from fixture_users union all select 'notifications:' || id from fixture_users);
    do $cleanup$ begin
      if to_regclass('points_private.returning_balances') is not null then
        delete from points_private.returning_balances where email_fingerprint in (${receipts});
      end if;
    end $cleanup$;
    delete from points_private.starter_grant_claims where email_fingerprint in (${receipts});
    select exists (select from auth.users where email in (${emails}))
        or exists (select from public.profiles where id in (select id from fixture_users))
        or exists (select from public.conversations where id in (select id from fixture_chats))
        or exists (select from points_private.starter_grant_claims where email_fingerprint in (${receipts}));
    commit;`);
  assert.equal(remaining, 'f', 'Disposable identities and their data were removed');
  for (const { email } of fixtures) issued.delete(email);
}

module.exports = { createStudentFixture, cleanupStudentFixtures, localClientConfig, countStudentFixtureReports, localSql: sql };
