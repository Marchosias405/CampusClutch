select pg_temp.login(6);
select is(public.get_my_notification_unread_count_v3(),1,'Direct warning appears exactly once');
select ok((select body like '%Please follow the community rules.%' and actor_id is null from public.get_my_notifications_v3()),'Warning includes explanation without admin identity');
select pg_temp.login(4);
select pg_temp.act('student',pg_temp.uid(6),'warn',511);
insert into results values('third-warning',pg_temp.act('student',pg_temp.uid(6),'warn',512));
select is(pg_temp.result('third-warning')->>'automatic_suspension','true','Third direct warning suspends');
select pg_temp.login(6);
select is(public.get_my_account_standing()->>'suspended','true','Suspension enforced');
select ok(public.get_my_account_standing()::text like '%Please follow the community rules.%','Blocked student sees reason');
select pg_temp.login(4);
