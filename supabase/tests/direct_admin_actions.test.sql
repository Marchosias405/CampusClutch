begin;
create extension if not exists pgtap with schema extensions;
set search_path=public,extensions;
select no_plan();
create function pg_temp.uid(i integer) returns uuid language sql immutable as $$
 select ('d1aece00-0000-4000-8000-'||lpad(i::text,12,'0'))::uuid; $$;
create function pg_temp.login(i integer) returns void language plpgsql as $$ begin
 perform set_config('request.jwt.claim.sub',pg_temp.uid(i)::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',pg_temp.uid(i),'role','authenticated','session_id',pg_temp.uid(i+100))::text,true);
end $$;
create temp table results(name text primary key,value jsonb); grant all on results to authenticated;
create function pg_temp.result(n text) returns jsonb language sql as $$select value from results where name=n;$$;
create function pg_temp.rid(n text) returns uuid language sql as $$select (value#>>'{}')::uuid from results where name=n;$$;
insert into auth.users(id,email,email_confirmed_at)
select pg_temp.uid(n),'direct-admin-'||n||'@tests.local',now() from generate_series(1,7) n;
update public.profiles set display_name='Direct fixture',onboarding_completed_at=now(),is_discoverable=true
where id in(select pg_temp.uid(n) from generate_series(1,7)n);
insert into auth.sessions(id,user_id,created_at,updated_at)
select pg_temp.uid(n+100),pg_temp.uid(n),now(),now() from generate_series(1,7)n;
select safety_private.assign_staff_role(pg_temp.uid(4),'admin',true,'Rollback only fixture');
select safety_private.assign_staff_role(pg_temp.uid(3),'moderator',true,'Rollback only fixture');
insert into public.academic_terms(id,code,display_name,year,season,starts_on,ends_on,status)
values(pg_temp.uid(301),'2088-fall','Direct fixture term',2088,'fall',current_date-30,current_date+30,'current');
insert into public.courses(id,code,title,term_id,status)
values(pg_temp.uid(201),'DIRECT 991','Direct fixture course',pg_temp.uid(301),'active');
insert into public.course_memberships(profile_id,course_id,status) values(pg_temp.uid(2),pg_temp.uid(201),'enrolled');
insert into course_reviews_private.reviews(id,course_code,term_id,author_id,difficulty,workload,recommend,grade,comment)
values(pg_temp.uid(200),'DIRECT 991',pg_temp.uid(301),pg_temp.uid(2),4,5,true,'B','Fixture review with useful feedback.');
create function pg_temp.context(t text,i uuid) returns jsonb language sql as $$select public.get_direct_moderation_context(t,i);$$;
create function pg_temp.act(t text,i uuid,k text,op integer,stamp timestamptz default null,reason text default 'Please follow the community rules.') returns jsonb language sql as $$
 select public.take_direct_moderation_action(t,i,pg_temp.uid(op),k,reason,coalesce(stamp,(pg_temp.context(t,i)->>'updated_at')::timestamptz));$$;
create function pg_temp.payload() returns jsonb language sql as $$select jsonb_build_object('category','delivery','title','Direct fixture request','description','Please help with this fixture request.',
 'campus_id',(select id from public.campuses where slug='burnaby'),'room_location','Library','deadline_at',clock_timestamp()+interval '1 day','points',30,
 'item_size','medium','details','{"pickup_location":"Cafe","dropoff_location":"Library"}'::jsonb);$$;
select ok(not has_function_privilege(role,'public.take_direct_moderation_action(text,uuid,uuid,text,text,timestamptz)','execute'),role||' cannot act') from unnest(array['anon','service_role']) role;
select ok(not has_table_privilege(role,'safety_private.direct_action_receipts','SELECT,INSERT,UPDATE,DELETE'),role||' cannot access receipts') from unnest(array['anon','authenticated','service_role']) role;
select ok(not has_function_privilege('authenticated','safety_private.remove_request(uuid)','execute'),'Internal removal inaccessible');
set local role authenticated;
select pg_temp.login(1);
select throws_ok($$select pg_temp.context('student',pg_temp.uid(2))$$,'42501',null,'Student cannot inspect admin context');
select throws_ok($$select pg_temp.act('student',pg_temp.uid(2),'warn',500)$$,'42501',null,'Student cannot warn');
select pg_temp.login(3);
select throws_ok($$select pg_temp.act('student',pg_temp.uid(2),'warn',500)$$,'42501',null,'Moderator cannot enforce');
select pg_temp.login(4);
select throws_ok($$select pg_temp.context('student',pg_temp.uid(4))$$,'42501',null,'Self action denied');
select throws_ok($$select pg_temp.context('student',pg_temp.uid(3))$$,'42501',null,'Staff target denied');
select throws_ok($$select pg_temp.context('message',pg_temp.uid(2))$$,'22023',null,'Unsupported target denied');
select throws_ok($$select pg_temp.act('student',pg_temp.uid(2),'remove_review',500)$$,'22023',null,'Wrong target/action denied');
select throws_ok($$select pg_temp.act('student',pg_temp.uid(2),'warn',500,null,'short')$$,'22023',null,'Short explanation denied');
insert into results values('review-context',pg_temp.context('course_review',pg_temp.uid(200)));
select is(pg_temp.result('review-context')#>>'{evidence,difficulty}','4','Admin sees review difficulty');
select is(pg_temp.result('review-context')#>>'{evidence,workload}','5','Admin sees review workload');
select ok(not(pg_temp.result('review-context')::text ~ '(author_id|subject_id|reporter_id)'),'Anonymous review context hides identities');
select throws_ok($$select pg_temp.act('course_review',pg_temp.uid(200),'remove_review',501,now()-interval '1 day')$$,'PT409',null,'Changed review rejected');
insert into results values('removed-review',pg_temp.act('course_review',pg_temp.uid(200),'remove_review',501));
select is(public.get_course_review_summary('DIRECT 991')->>'review_count','0','Direct removal updates course statistics');
select is(pg_temp.act('course_review',pg_temp.uid(200),'remove_review',501,(pg_temp.result('review-context')->>'updated_at')::timestamptz),pg_temp.result('removed-review'),'Retry reconciles already hidden target');
select throws_ok($$select pg_temp.act('course_review',pg_temp.uid(200),'remove_review',501,now())$$,'22023',null,'Retry fingerprint prevents different evidence');
select pg_temp.login(2);
select ok(exists(select 1 from public.get_my_notifications_v3() where title='Course review removed' and body like '%Please follow the community rules.%'),'Author gets removal explanation');
select ok(public.get_my_moderation_actions()::text like '%remove_review%','Review removal can be appealed');
reset role;
select ok((select removed_at is not null from course_reviews_private.reviews where id=pg_temp.uid(200)),'Review hidden in source');
select is((select origin from safety_private.reports where course_review_id=pg_temp.uid(200)),'admin_direct','Action records staff origin without student report');
select ok((select reporter_id is null from safety_private.reports where course_review_id=pg_temp.uid(200)),'No invented reporter');
set local role authenticated;
-- Build an accepted job through real APIs, then remove it as an uninvolved admin.
select pg_temp.login(1);
insert into results values('request',to_jsonb(public.save_my_request(pg_temp.payload())));
select pg_temp.login(2);
insert into results values('offer',to_jsonb(public.create_my_request_offer_for_terms(pg_temp.rid('request'),1,30)));
select pg_temp.login(1);
select public.decide_request_offer_for_round(pg_temp.rid('offer'),'accepted',1,30);
select is(public.get_my_points()->>'reserved','30','Acceptance reserved reward');
select pg_temp.login(4);
insert into results values('request-context',pg_temp.context('request',pg_temp.rid('request')));
reset role;
create function pg_temp.fail_admin_notice() returns trigger language plpgsql as $$begin
 if new.source_event_key like 'moderation-action:%' and new.recipient_id=pg_temp.uid(1) then raise exception 'fixture notification failure'; end if; return new;
end $$;
create trigger direct_fixture_notice_failure before insert on public.notifications for each row execute function pg_temp.fail_admin_notice();
set local role authenticated;
select throws_ok($$select pg_temp.act('request',pg_temp.rid('request'),'remove_request',502)$$,'P0001','fixture notification failure','Notification failure rolls back direct removal');
select pg_temp.login(1);
select is(public.get_my_points()->>'reserved','30','Failed action keeps reservation');
select is((select status from public.requests where id=pg_temp.rid('request')),'accepted','Failed action keeps assignment');
reset role;
drop trigger direct_fixture_notice_failure on public.notifications;
set local role authenticated;
select pg_temp.login(4);
insert into results values('removed-request',pg_temp.act('request',pg_temp.rid('request'),'remove_request',502));
select is(pg_temp.act('request',pg_temp.rid('request'),'remove_request',502,(pg_temp.result('request-context')->>'updated_at')::timestamptz),pg_temp.result('removed-request'),'Request removal exact retry');
select pg_temp.login(1);
select is(public.get_my_points()->>'reserved','0','Admin removal releases held reward');
select is(public.get_my_points()->>'balance','100','Admin removal does not charge poster');
select is((select status from public.requests where id=pg_temp.rid('request')),'cancelled','Removed assignment closed');
select ok(exists(select 1 from public.get_my_notifications_v3() where title='Request removed' and body like '%Please follow the community rules.%'),'Owner notified with removal reason');
insert into results values('request-appeal',to_jsonb(public.submit_moderation_appeal((pg_temp.result('removed-request')->>'action_id')::uuid,pg_temp.uid(600),'Please reconsider this request removal.')));
select pg_temp.login(2);
select is(public.get_my_points()->>'balance','100','Helper not paid for removed job');
select is((select count(*)::int from public.requests where id=pg_temp.rid('request')),0,'Removed request hidden from helper');
select pg_temp.login(5);
select is((select count(*)::int from public.requests where id=pg_temp.rid('request')),0,'Removed request hidden from unrelated student');
select pg_temp.login(4);
select public.get_moderation_appeal(pg_temp.rid('request-appeal'));
select lives_ok($$select public.resolve_moderation_appeal(pg_temp.rid('request-appeal'),pg_temp.uid(601),0,'overturned','This request is safe after reviewing the details.')$$,'Admin can overturn direct removal');
select pg_temp.login(1);
select is(public.get_my_points()->>'reserved','0','Overturn never recreates hold');
select is((select status from public.requests where id=pg_temp.rid('request')),'cancelled','Overturn never reassigns helper');
select pg_temp.login(5);
select is((select count(*)::int from public.requests where id=pg_temp.rid('request')),0,'Closed request stays outside public feed after appeal');
reset role;
select ok((select moderation_removed_at is null from public.requests where id=pg_temp.rid('request')),'Appeal clears removal flag');
set local role authenticated;
select pg_temp.login(4);
-- Completed payments and accepted-helper history survive content removal.
select pg_temp.login(1);
insert into results values('completed',to_jsonb(public.save_my_request(pg_temp.payload())));
select throws_ok($$update public.requests set moderation_removed_at=now() where id=pg_temp.rid('completed')$$,'42501',null,'Student cannot mark content removed');
select pg_temp.login(2);
insert into results values('completed-offer',to_jsonb(public.create_my_request_offer_for_terms(pg_temp.rid('completed'),1,30)));
